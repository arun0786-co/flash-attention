"""results/<gpu>/attention.csv into results/summary.md and figures/{time,memory}.png.

    python analysis/report.py
"""

import csv
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "results"
FIGURES = ROOT / "figures"
SUMMARY = RESULTS / "summary.md"
GPU = "rtx2080ti"
COLOR = {"flash": "#2a78d6", "standard": "#eb6834"}
INK, MUTED, GRID = "#1f1f1e", "#6b6a64", "#e4e3de"


def read(path):
    rows = []
    for r in csv.DictReader(open(path)):
        rows.append({k: (float(v) if v not in ("", None) and k not in ("method",) else v) for k, v in r.items()})
    return rows


def ran(r):
    return r["fwd_ms"] not in ("", None)


def table(rows):
    """{(method, causal, n): row}"""
    return {(r["method"], int(r["causal"]), int(r["n"])): r for r in rows}


def summary(rows):
    t = table(rows)
    ns = sorted({int(r["n"]) for r in rows})
    out = ["# Summary", "", "Generated by `analysis/report.py` from `results/rtx2080ti/attention.csv`. 16 heads of",
           "dimension 64, fp16. Times in milliseconds; TFLOPS count the matrix multiplies only (2 forward, 5",
           "backward; the causal mask halves both).", ""]
    for causal in (0, 1):
        out += [f"## {'Causal' if causal else 'No mask'}", "",
                "| N | flash fwd | standard fwd | flash bwd | standard bwd | flash fwd+bwd TFLOPS | standard | flash extra MB | standard extra MB | max diff in O |",
                "|---|---|---|---|---|---|---|---|---|---|"]
        for n in ns:
            f, s = t[("flash", causal, n)], t[("standard", causal, n)]
            def ms(r, k):
                return f"{r[k]:.3f}" if ran(r) else "out of memory"
            def tf(r):
                if not ran(r):
                    return "-"
                total_flop = r["fwd_tflops"] * r["fwd_ms"] + r["bwd_tflops"] * r["bwd_ms"]  # TFLOPS x ms = GFLOP
                return f"{total_flop / (r['fwd_ms'] + r['bwd_ms']):.1f}"
            out.append(f"| {n:,} | {ms(f, 'fwd_ms')} | {ms(s, 'fwd_ms')} | {ms(f, 'bwd_ms')} | {ms(s, 'bwd_ms')} | "
                       f"{tf(f)} | {tf(s)} | {f['extra_mb']:,.1f} | {s['extra_mb']:,.1f} | "
                       f"{f['max_diff_o']:.4f} |" if f["max_diff_o"] >= 0 else
                       f"| {n:,} | {ms(f, 'fwd_ms')} | {ms(s, 'fwd_ms')} | {ms(f, 'bwd_ms')} | {ms(s, 'bwd_ms')} | "
                       f"{tf(f)} | {tf(s)} | {f['extra_mb']:,.1f} | {s['extra_mb']:,.1f} | - |")
        out.append("")
    return out


def style(ax):
    for s in ("top", "right"):
        ax.spines[s].set_visible(False)
    for s in ("left", "bottom"):
        ax.spines[s].set_color(GRID)
    ax.tick_params(colors=MUTED, labelsize=8)
    ax.grid(axis="y", color=GRID, lw=0.8)
    ax.set_axisbelow(True)
    ax.set_xscale("log", base=2)
    ax.set_yscale("log")


def plot(rows):
    t = table(rows)
    ns = sorted({int(r["n"]) for r in rows})
    FIGURES.mkdir(exist_ok=True)
    # time for forward + backward
    fig, ax = plt.subplots(figsize=(7, 4.2), dpi=150)
    for method in ("flash", "standard"):
        for causal, dash in ((0, "-"), (1, (0, (4, 3)))):
            pts = [(n, t[(method, causal, n)]["fwd_ms"] + t[(method, causal, n)]["bwd_ms"]) for n in ns
                   if ran(t[(method, causal, n)])]
            ax.plot([p[0] for p in pts], [p[1] for p in pts], color=COLOR[method], ls=dash, lw=2, marker="o", ms=4)
            last = pts[-1]
            ax.annotate(f"{method}{', causal' if causal else ''}", last, textcoords="offset points",
                        xytext=(6, 4 if method == "standard" and not causal else -8 if method == "standard" else -3),
                        fontsize=8, color=INK)
    style(ax)
    ax.set_xticks(ns, [f"{n:,}" for n in ns], fontsize=8)
    ax.minorticks_off()
    ax.set_xlabel("sequence length N (16 heads of dimension 64)", color=MUTED)
    ax.set_ylabel("forward + backward, ms", color=MUTED)
    ax.set_xlim(ns[0] / 1.3, ns[-1] * 2.6)
    ax.set_title("Attention time on an RTX 2080 Ti", fontsize=11, color=INK, loc="left")
    fig.tight_layout()
    fig.savefig(FIGURES / "time.png")
    plt.close(fig)
    # extra memory
    fig, ax = plt.subplots(figsize=(7, 4.2), dpi=150)
    for method in ("flash", "standard"):
        fit = [(n, t[(method, 0, n)]["extra_mb"]) for n in ns if ran(t[(method, 0, n)])]
        ax.plot([p[0] for p in fit], [p[1] for p in fit], color=COLOR[method], lw=2, marker="o", ms=4)
        ax.annotate(method, fit[-1], textcoords="offset points", xytext=(6, -3), fontsize=8, color=INK)
        for n in ns:  # what standard attention would have needed where it did not fit
            r = t[(method, 0, n)]
            if not ran(r):
                ax.scatter([n], [r["extra_mb"]], s=30, facecolor="white", edgecolor=COLOR[method], zorder=3)
                ax.annotate(f"would need {r['extra_mb'] / 1000:.1f} GB", (n, r["extra_mb"]), textcoords="offset points",
                            xytext=(-6, 6), ha="right", fontsize=8, color=INK)
    card_mb = 11264 * 1.048576  # 11,264 MiB in MB, the unit of the y axis
    ax.axhline(card_mb, color=MUTED, lw=1, ls=(0, (4, 3)))
    ax.annotate("the card's memory, 11,264 MiB", (ns[0], card_mb), textcoords="offset points", xytext=(0, 4),
                fontsize=8, color=MUTED)
    style(ax)
    ax.set_xticks(ns, [f"{n:,}" for n in ns], fontsize=8)
    ax.minorticks_off()
    ax.set_xlabel("sequence length N (16 heads of dimension 64)", color=MUTED)
    ax.set_ylabel("memory beyond inputs and outputs, MB", color=MUTED)
    ax.set_xlim(ns[0] / 1.3, ns[-1] * 2.2)
    ax.set_title("Extra memory: O(N) against O(N²)", fontsize=11, color=INK, loc="left")
    fig.tight_layout()
    fig.savefig(FIGURES / "memory.png")
    plt.close(fig)


def main(quiet=False):
    rows = read(RESULTS / GPU / "attention.csv")
    out = summary(rows)
    SUMMARY.write_text("\n".join(out) + "\n")
    plot(rows)
    if not quiet:
        print("\n".join(out))


if __name__ == "__main__":
    main()
